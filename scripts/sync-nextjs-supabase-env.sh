#!/usr/bin/env bash
# Writes nextjs/.env.local Supabase settings from k8s/keycloak/supabase.env (+ optional keys).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
KC_ENV="${REPO_ROOT}/k8s/keycloak/supabase.env"
SHOP_ENV="${REPO_ROOT}/k8s/shop/shop.env"
OUT="${REPO_ROOT}/nextjs/.env.local"

if [[ ! -f "$KC_ENV" ]]; then
  echo "Missing ${KC_ENV}"
  exit 1
fi

set -a
# shellcheck disable=SC1090
source "$KC_ENV"
set +a

PROJECT_REF="${KC_DB_USERNAME#postgres.}"
if [[ "$PROJECT_REF" == "$KC_DB_USERNAME" ]]; then
  echo "Could not derive Supabase project ref from KC_DB_USERNAME (${KC_DB_USERNAME})"
  exit 1
fi

if [[ "$KC_DB_URL" =~ jdbc:postgresql://([^:/]+):([0-9]+)/([^?]+) ]]; then
  PG_HOST="${BASH_REMATCH[1]}"
  PG_PORT="${BASH_REMATCH[2]}"
  PG_DB="${BASH_REMATCH[3]}"
else
  echo "Could not parse host from KC_DB_URL"
  exit 1
fi

ENC_PASS="$(python3 - <<'PY'
import os, urllib.parse
print(urllib.parse.quote(os.environ["KC_DB_PASSWORD"], safe=""))
PY
)"

DATABASE_URL="postgresql://${KC_DB_USERNAME}:${ENC_PASS}@${PG_HOST}:${PG_PORT}/${PG_DB}?sslmode=require"

SUPABASE_URL="NEXT_PUBLIC_SUPABASE_URL=https://${PROJECT_REF}.supabase.co"
SUPABASE_KEYS=""
if [[ -f "$SHOP_ENV" ]]; then
  set -a
  # shellcheck disable=SC1090
  source "$SHOP_ENV"
  set +a
fi

if [[ -n "${SUPABASE_SERVICE_ROLE_KEY:-}" ]]; then
  SUPABASE_KEYS=$'SUPABASE_SERVICE_ROLE_KEY='"${SUPABASE_SERVICE_ROLE_KEY}"$'\n'
elif [[ -n "${SUPABASE_ANON_KEY:-}" ]]; then
  SUPABASE_KEYS=$'SUPABASE_ANON_KEY='"${SUPABASE_ANON_KEY}"$'\n'
fi

{
  echo "# Generated by scripts/sync-nextjs-supabase-env.sh — do not commit"
  echo "$SUPABASE_URL"
  echo "DATABASE_URL=${DATABASE_URL}"
  echo -n "$SUPABASE_KEYS"
  if [[ -f "$SHOP_ENV" ]]; then
    echo ""
    echo "# Auth.js (from k8s/shop/shop.env)"
    grep -E '^AUTH_' "$SHOP_ENV" || true
  fi
} > "$OUT"

echo "Wrote ${OUT}"
